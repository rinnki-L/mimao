/// 繁体 → 简体（由上表反查；一对多时取最后一个）。
final Map<String, String> novelTraditionalToSimplified = () {
  final map = <String, String>{};
  for (final entry in novelSimplifiedToTraditional.entries) {
    map[entry.value] = entry.key;
  }
  return Map<String, String>.unmodifiable(map);
}();

/// 按 [mode] 转换 [input]；[NovelChineseConvert.none] 原样返回。
String convertNovelChinese(String input, NovelChineseConvert mode) {
  if (input.isEmpty || mode == NovelChineseConvert.none) return input;
  final map = mode == NovelChineseConvert.simplifiedToTraditional
      ? novelSimplifiedToTraditional
      : novelTraditionalToSimplified;
  final buffer = StringBuffer();
  for (final rune in input.runes) {
    final char = String.fromCharCode(rune);
    buffer.write(map[char] ?? char);
  }
  return buffer.toString();
}
